// Project-folder copies and the revision log.
//
// A job's "File location" is its project folder on the network share. The
// board keeps two things there up to date, and nothing else:
//   <folder>/BoardReview/<JOB>/<drawing>/attempt <n>.pdf      submitted PDFs under review
//   <folder>/BoardReview/<JOB>/<drawing> - board reviewed (attempt <n>).pdf
//                                                             the exact PDF that passed
//   <folder>/REVISION_LOG.md                                  generated from board history
//
// Rules (decision #26):
//   * The board only replaces or deletes a file it wrote itself (recorded in
//     project_files) and only while its content is still what the board wrote.
//     Anything else with the same name is left alone and reported.
//   * Signed scans, CAD files and every other file in the folder are never
//     written, moved or deleted. Signed scans are not even copied here.
//   * The share may be offline: the board's own storage stays the source of
//     truth, and the copies are retried until they succeed.

import { createHash } from 'node:crypto';
import { copyFile, mkdir, readFile, rename, rm, stat, writeFile } from 'node:fs/promises';
import { join, resolve, sep } from 'node:path';
import { DRAWING_STATE_LABEL, type ReviewWorkspace } from '@board/shared';
import { all, get, run } from '../db/connection.ts';
import { nowIso } from '../lib/core.ts';
import { blobPath, hasBlob, type StoreCtx } from './reviewStore.ts';
import { workspace, localDay } from './reviews.ts';
import { getUser } from './users.ts';

const LOG_NAME = 'REVISION_LOG.md';
export const folderKey = (folder: string) => folder.trim().replace(/[\\/]+$/, '').toLowerCase();
const safeName = (s: string) => s.replace(/[\\/:*?"<>|\u0000-\u001f]/g, '_').replace(/[. ]+$/, '').slice(0, 120) || '_';

export function reviewedName(identifier: string, attempt: number) {
  return `${safeName(identifier)} - board reviewed (attempt ${attempt}).pdf`;
}

function setSync(ctx: StoreCtx, ticketId: number, state: 'ok' | 'pending' | 'failed' | 'no_folder', detail: string | null) {
  run(
    ctx.db,
    `INSERT INTO review_sync (ticket_id, state, detail, updated_at) VALUES (?, ?, ?, ?)
     ON CONFLICT(ticket_id) DO UPDATE SET state = excluded.state, detail = excluded.detail, updated_at = excluded.updated_at`,
    ticketId,
    state,
    detail,
    nowIso(ctx),
  );
  ctx.events.emit({ type: 'ticket', id: ticketId, by: null });
  ctx.events.flush();
}

/** Mark a job's copies as needing an update (shown until the next sync finishes). */
export function markSyncPending(ctx: StoreCtx, ticketId: number) {
  const folder = get<{ file_location: string }>(ctx.db, 'SELECT file_location FROM tickets WHERE id = ?', ticketId)?.file_location ?? '';
  run(
    ctx.db,
    `INSERT INTO review_sync (ticket_id, state, detail, updated_at) VALUES (?, ?, NULL, ?)
     ON CONFLICT(ticket_id) DO UPDATE SET state = excluded.state, detail = NULL, updated_at = excluded.updated_at`,
    ticketId,
    folder.trim() ? 'pending' : 'no_folder',
    nowIso(ctx),
  );
}

const sha256 = (b: Buffer | string) => createHash('sha256').update(b).digest('hex');
async function fileSha(path: string): Promise<string | null> {
  try {
    return sha256(await readFile(path));
  } catch (e) {
    if ((e as NodeJS.ErrnoException).code === 'ENOENT') return null;
    throw e;
  }
}

