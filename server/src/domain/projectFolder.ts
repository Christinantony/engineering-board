/** The REVISION_LOG.md text for every job whose File location is `folder`. */
export function revisionLog(ctx: StoreCtx, folder: string, onlyTicket?: number): string {
  const key = folderKey(folder);
  const ids = onlyTicket
    ? [onlyTicket]
    : all<{ id: number; file_location: string }>(
        ctx.db,
        `SELECT DISTINCT t.id, t.file_location FROM tickets t JOIN review_drawings d ON d.ticket_id = t.id ORDER BY t.job_number`,
      )
        .filter((r) => folderKey(r.file_location) === key)
        .map((r) => r.id);
  const name = (id: number | null) => (id == null ? 'the board' : getUser(ctx, id)?.name ?? `user #${id}`);
  const when = (iso: string | null) =>
    iso
      ? `${localDay(ctx, iso)} ${new Intl.DateTimeFormat('en-GB', { timeZone: ctx.tz, hour: '2-digit', minute: '2-digit', hourCycle: 'h23' }).format(new Date(iso))}`
      : '';
  const oneLine = (s: string | null | undefined) => (s ?? '').replace(/\r?\n+/g, ' ').trim();
  const lines: string[] = [
    '# Revision log',
    '',
    `Generated by Engineering Board from its review history. Do not edit: the board rewrites this file. Last updated ${when(nowIso(ctx))}.`,
    '',
    '> Board review is an internal check. It is **not** official approval: the physically signed drawing is the approved record, and the signed scans in this folder remain the official reference.',
    '',
  ];
  for (const id of ids) {
    const w: ReviewWorkspace = workspace(ctx, id);
    const t = w.ticket;
    lines.push(`## ${t.job_number} · ${oneLine(t.title)}`, '');
    if (w.references.length)
      lines.push(`Signed reference scans: ${w.references.map((r) => `${r.filename} (${r.pages} pages, attached ${localDay(ctx, r.attached_at)} by ${name(r.attached_by)})`).join('; ')}`, '');
    for (const d of w.drawings) {
      lines.push(`### ${d.identifier} · ${d.kind === 'new' ? 'new drawing' : 'revision'} · ${DRAWING_STATE_LABEL[d.state]}`, '');
      if (d.ref_page && d.ref_reference_id) {
        const r = w.references.find((x) => x.id === d.ref_reference_id);
        if (r) lines.push(`- Reference page: page ${d.ref_page} of ${r.filename}`);
      }
      for (const a of d.attempts) {
        lines.push(`- **Attempt ${a.number}** · ${a.filename} · submitted by ${name(a.submitted_by)}, ${when(a.submitted_at)} (submission ${a.submission_number})`);
        lines.push(`  - ${d.kind === 'new' && a.number === 1 ? 'Purpose' : 'What changed and why'}: ${oneLine(a.notes)}`);
        for (const c of d.comments.filter((c) => c.attempt_id === a.id)) {
          lines.push(`  - Comment by ${name(c.user_id)}, ${when(c.created_at)}: ${oneLine(c.body)}`);
          if (c.response) lines.push(`    - Correction response by ${name(c.response_by)}, ${when(c.response_at)}: ${oneLine(c.response)}`);
          if (c.resolved_at) lines.push(`    - Resolved by ${name(c.resolved_by)}, ${when(c.resolved_at)}`);
        }
        if (a.outcome === 'passed')
          lines.push(`  - Outcome: board review passed by ${name(a.decided_by)}, ${when(a.decided_at)}${a.decision_note ? `: ${oneLine(a.decision_note)}` : ''} (internal review, not official approval)`);
        else if (a.outcome === 'returned')
          lines.push(`  - Outcome: returned for correction by ${name(a.decided_by)}, ${when(a.decided_at)}${a.decision_note ? `: ${oneLine(a.decision_note)}` : ''}`);
        else if (a.outcome === 'superseded') lines.push(`  - Outcome: replaced by a newer attempt before a decision`);
        else lines.push(`  - Outcome: awaiting board review`);
        if (a.file_removed_at) lines.push(`  - Intermediate PDF removed after board review (${localDay(ctx, a.file_removed_at)})`);
        else if (a.id === d.passed_attempt_id) lines.push(`  - Kept as the reviewed PDF: BoardReview/${t.job_number}/${reviewedName(d.identifier, a.number)}`);
      }
      if (d.handover_at) lines.push(`- Handed over for signature: ${when(d.handover_at)}, recorded by ${name(d.handover_by)}; ${name(d.passed_by)} reminded`);
      if (d.signed_at) lines.push(`- Physically signed: recorded ${when(d.signed_at)} by ${name(d.signed_by)}`);
      for (const e of w.events.filter((e) => e.drawing_id === d.id && ['withdrawn', 'renamed'].includes(e.kind)))
        lines.push(`- ${e.kind === 'withdrawn' ? 'Withdrawn' : 'Number corrected'}: ${when(e.at)} by ${name(e.user_id)}${e.detail ? `: ${oneLine(e.detail)}` : ''}`);
      if (d.cleanup !== 'none')
        lines.push(
          `- Intermediate-file clean-up: ${d.cleanup === 'done' ? 'done' : d.cleanup === 'pending' ? 'pending' : `failed, will retry (${oneLine(d.cleanup_detail)})`}`,
        );
      lines.push('');
    }
  }
  return lines.join('\n');
}

