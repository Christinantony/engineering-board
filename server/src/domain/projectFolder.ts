const queues = new Map<string, Promise<unknown>>();

/** Bring a job's project-folder copies up to date. Runs one at a time per folder. */
export function syncProjectFolder(ctx: StoreCtx, ticketId: number): Promise<void> {
  const folder = get<{ file_location: string }>(ctx.db, 'SELECT file_location FROM tickets WHERE id = ?', ticketId)?.file_location ?? '';
  const key = folderKey(folder) || `#${ticketId}`;
  const prev = queues.get(key) ?? Promise.resolve();
  const next = prev.then(() => doSync(ctx, ticketId)).catch((e) => {
    try {
      setSync(ctx, ticketId, 'failed', (e as Error).message);
    } catch {
      /* database closed (shutdown) */
    }
  });
  queues.set(key, next);
  void next.finally(() => {
    if (queues.get(key) === next) queues.delete(key);
  });
  return next;
}

/** Wait for every queued folder update (tests and shutdown). */
export async function settleSyncs() {
  while (queues.size) await Promise.all([...queues.values()]);
}

async function doSync(ctx: StoreCtx, ticketId: number): Promise<void> {
  if (!ctx.db.isOpen) return;
  const t = get<{ job_number: string; file_location: string }>(ctx.db, 'SELECT job_number, file_location FROM tickets WHERE id = ?', ticketId);
  if (!t) return;
  // nothing to copy yet (only a signed scan attached): scans are never copied
  if (!get(ctx.db, 'SELECT 1 FROM review_drawings WHERE ticket_id = ?', ticketId)) return setSync(ctx, ticketId, 'ok', null);
  const folder = t.file_location.trim();
  if (!folder) return setSync(ctx, ticketId, 'no_folder', 'Set the job\'s File location to its project folder to keep copies and the revision log there.');
  const root = resolve(folder);
  try {
    const st = await stat(root);
    if (!st.isDirectory()) throw new Error('not a folder');
  } catch (e) {
    const code = (e as NodeJS.ErrnoException).code;
    return setSync(ctx, ticketId, 'failed', `Can't reach the project folder ${folder} (${code ?? (e as Error).message}). The board keeps its own copies and will try again.`);
  }
  const key = folderKey(folder);
  const inside = (p: string) => {
    const full = resolve(p);
    if (!full.startsWith(root + sep)) throw new Error(`refusing to write outside the project folder: ${p}`);
    return full;
  };

  // what should be there
  const desired = new Map<string, { sha: string; source: string | Buffer }>();
  const job = safeName(t.job_number);
  const drawings = all<{ id: number; identifier: string; passed_attempt_id: number | null; state: string }>(
    ctx.db,
    'SELECT id, identifier, passed_attempt_id, state FROM review_drawings WHERE ticket_id = ?',
    ticketId,
  );
  const problems: string[] = [];
  for (const d of drawings) {
    const attempts = all<{ id: number; number: number; sha256: string; file_removed_at: string | null }>(
      ctx.db,
      'SELECT id, number, sha256, file_removed_at FROM review_attempts WHERE drawing_id = ?',
      d.id,
    );
    for (const a of attempts) {
      if (a.file_removed_at) continue;
      const isFinal = a.id === d.passed_attempt_id && ['passed', 'handed_over', 'signed'].includes(d.state);
      const rel = isFinal ? ['BoardReview', job, reviewedName(d.identifier, a.number)] : ['BoardReview', job, safeName(d.identifier), `attempt ${a.number}.pdf`];
      if (!hasBlob(ctx, a.sha256)) {
        problems.push(`${d.identifier} attempt ${a.number}: the board's copy is missing`);
        continue;
      }
      desired.set(rel.join('/'), { sha: a.sha256, source: blobPath(ctx, a.sha256) });
    }
  }
  const log = Buffer.from(revisionLog(ctx, folder), 'utf8');
  const logSha = sha256(log);

  const recorded = all<{ id: number; path: string; sha256: string; ticket_id: number | null; removed_at: string | null }>(
    ctx.db,
    'SELECT id, path, sha256, ticket_id, removed_at FROM project_files WHERE folder = ?',
    key,
  );
  const byPath = new Map(recorded.map((r) => [r.path, r]));
  const record = (path: string, sha: string) =>
    run(
      ctx.db,
      `INSERT INTO project_files (folder, path, ticket_id, sha256, written_at) VALUES (?, ?, ?, ?, ?)
       ON CONFLICT(folder, path) DO UPDATE SET sha256 = excluded.sha256, ticket_id = excluded.ticket_id, written_at = excluded.written_at, removed_at = NULL`,
      key,
      path,
      path === LOG_NAME ? null : ticketId,
      sha,
      nowIso(ctx),
    );

  // 1. copies of PDFs under review and the reviewed finals
  for (const [rel, want] of desired) {
    const target = inside(join(root, ...rel.split('/')));
    try {
      const have = await fileSha(target);
      if (have === want.sha) {
        if (byPath.get(rel)?.sha256 !== want.sha || byPath.get(rel)?.removed_at) record(rel, want.sha);
        continue;
      }
      if (have != null) {
        const mine = byPath.get(rel);
        if (!mine || mine.removed_at || mine.sha256 !== have) {
          problems.push(`${rel} already exists and was not written by the board, so it was left alone`);
          continue;
        }
      }
      await mkdir(resolve(target, '..'), { recursive: true });
      const tmp = `${target}.board-partial`;
      await copyFile(want.source as string, tmp);
      if ((await fileSha(tmp)) !== want.sha) {
        await rm(tmp, { force: true });
        throw new Error('the copy did not match the board\'s file');
      }
      await rename(tmp, target);
      record(rel, want.sha);
    } catch (e) {
      problems.push(`${rel}: ${(e as NodeJS.ErrnoException).code ?? (e as Error).message}`);
    }
  }

  // 2. remove copies of intermediate PDFs the board wrote and no longer needs
  for (const r of recorded) {
    if (r.removed_at || r.ticket_id !== ticketId || r.path === LOG_NAME || desired.has(r.path)) continue;
    const target = inside(join(root, ...r.path.split('/')));
    try {
      const have = await fileSha(target);
      if (have == null || have === r.sha256) {
        if (have != null) await rm(target, { force: true });
        run(ctx.db, 'UPDATE project_files SET removed_at = ? WHERE id = ?', nowIso(ctx), r.id);
      } else problems.push(`${r.path} was changed after the board wrote it, so it was not removed`);
    } catch (e) {
      problems.push(`removing ${r.path}: ${(e as NodeJS.ErrnoException).code ?? (e as Error).message}`);
    }
  }

  // 3. the revision log
  const logPath = inside(join(root, LOG_NAME));
  try {
    const have = await fileSha(logPath);
    const mine = byPath.get(LOG_NAME);
    if (have !== logSha) {
      if (have != null && (!mine || mine.sha256 !== have)) {
        problems.push(`${LOG_NAME} exists but was not written by the board (or was edited), so it was not replaced. Rename it to let the board write its log.`);
      } else {
        const tmp = `${logPath}.board-partial`;
        await writeFile(tmp, log);
        await rename(tmp, logPath);
        record(LOG_NAME, logSha);
      }
    }
  } catch (e) {
    problems.push(`${LOG_NAME}: ${(e as NodeJS.ErrnoException).code ?? (e as Error).message}`);
  }

  setSync(ctx, ticketId, problems.length ? 'failed' : 'ok', problems.length ? problems.join('; ') : null);
}

/** Jobs whose copies are pending or failed (retried by maintenance). */
export function jobsNeedingSync(ctx: StoreCtx): number[] {
  return all<{ ticket_id: number }>(ctx.db, `SELECT ticket_id FROM review_sync WHERE state IN ('pending','failed')`).map((r) => r.ticket_id);
}
